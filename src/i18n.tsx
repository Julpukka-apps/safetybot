type I18nValue = {
  language: string;
  setLanguage: (id: string) => void;
  t: (key: string) => string;
  label: (kind: "field" | "case" | "opt", id: string, fallback: string) => string;
};

const I18nContext = createContext<I18nValue>({
  language: "en",
  setLanguage: () => undefined,
  t: (key) => en[key] || key,
  label: (_kind, _id, fallback) => fallback,
});

function browserLanguage(): string {
  if (typeof navigator === "undefined") return "en";
  const code = navigator.language.slice(0, 2).toLowerCase();
  return LANGUAGES.some((item) => item.id === code) ? code : "en";
}

function uiLanguage(language: string): string {
  if (language && language !== "auto") return language;
  return browserLanguage();
}

export function activeLanguage(language: string): string {
  return uiLanguage(language);
}

function savedLanguage(): string | null {
  if (typeof window === "undefined") return null;
  const saved = localStorage.getItem(LANG_KEY) || sessionStorage.getItem(LANG_KEY);
  return saved && LANGUAGES.some((item) => item.id === saved) ? saved : null;
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState("en");

  useEffect(() => {
    setLanguageState(savedLanguage() || "auto");
  }, []);

  useEffect(() => {
    const ui = uiLanguage(language);
    document.documentElement.lang = ui;
    document.documentElement.dir = RTL.has(ui) ? "rtl" : "ltr";
  }, [language]);

  const value = useMemo<I18nValue>(() => {
    const ui = uiLanguage(language);
    const pack = { ...en, ...(extraPacks[ui] || {}), ...(morePacks[ui] || {}), ...(packs[ui] || {}) };
    const t = (key: string) => pack[key] || en[key] || key;
    return {
      language,
      setLanguage: (id: string) => {
        if (!LANGUAGES.some((item) => item.id === id)) return;
        setLanguageState(id);
        localStorage.setItem(LANG_KEY, id);
        sessionStorage.setItem(LANG_KEY, id);
      },
      t,
      label: (kind, id, fallback) => {
        const key = `${kind}.${id}`;
        const text = pack[key] || en[key];
        return text || fallback;
      },
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
